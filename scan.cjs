var MIN_BARS = 55;
function trendOf(c, tf) {
  if (!c) return { tf, trend: "MIXED", close: null, ema21: null, ema50: null, bars: 0, ready: false, note: "not fetched" };
  if (c.length < MIN_BARS) {
    return { tf, trend: "MIXED", close: null, ema21: null, ema50: null, bars: c.length, ready: false, note: `only ${c.length} bars (need ${MIN_BARS})` };
  }
  const closes = c.map((x) => x.c);
  const e21 = ema(closes, 21), e50 = ema(closes, 50);
  const i = closes.length - 1;
  const close = closes[i], a = e21[i], b = e50[i];
  const trend = close > a && a > b ? "UP" : close < a && a < b ? "DOWN" : "MIXED";
  const rel = close > a ? "above" : "below";
  return {
    tf,
    trend,
    close,
    ema21: a,
    ema50: b,
    bars: c.length,
    ready: true,
    note: `close ${rel} EMA21, EMA21 ${a > b ? "above" : "below"} EMA50`
  };
}
function alignment(h1, h4) {
  if (!h1.ready || !h4.ready) {
    return { side: null, text: "H1/H4 trend not available yet, so no potential entries are plotted" };
  }
  if (h1.trend === "UP" && h4.trend === "UP") return { side: "BUY", text: "H1 UP and H4 UP: BUY entries only" };
  if (h1.trend === "DOWN" && h4.trend === "DOWN") return { side: "SELL", text: "H1 DOWN and H4 DOWN: SELL entries only" };
  return { side: null, text: `H1 ${h1.trend} and H4 ${h4.trend} do not agree: no potential entries are plotted` };
}

