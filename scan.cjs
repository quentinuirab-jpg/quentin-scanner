function derivCandles(symbol, granularity, count, timeoutMs = 15e3) {
  return new Promise((resolve, reject) => {
    let ws;
    try {
      ws = new WebSocket(DERIV_WS);
    } catch (e) {
      reject(e);
      return;
    }
    let settled = false;
    let timer;
    const finish = (fn) => {
      if (settled) return;
      settled = true;
      if (timer) clearTimeout(timer);
      try {
        ws.close();
      } catch {
      }
      fn();
    };
    timer = setTimeout(() => finish(() => reject(new Error(`Deriv ${symbol}: timeout`))), timeoutMs);
    ws.onopen = () => ws.send(JSON.stringify({ ticks_history: symbol, style: "candles", granularity, count, end: "latest", adjust_start_time: 1 }));
    ws.onmessage = (ev) => {
      let msg;
      try {
        msg = JSON.parse(String(ev.data));
      } catch {
        return;
      }
      if (msg.error) {
        finish(() => {
          const err = new Error(`Deriv ${symbol}: ${msg.error.message ?? msg.error.code ?? "API error"}`);
          err.status = 400;
          reject(err);
        });
        return;
      }
      if (Array.isArray(msg.candles)) {
        const out = msg.candles.map((c) => ({ t: Number(c.epoch) * 1e3, o: +c.open, h: +c.high, l: +c.low, c: +c.close })).filter((c) => [c.t, c.o, c.h, c.l, c.c].every(Number.isFinite)).sort((a, b) => a.t - b.t);
        finish(() => resolve(out));
      }
    };
    ws.onerror = () => finish(() => reject(new Error(`Deriv ${symbol}: connection error`)));
    ws.onclose = () => finish(() => reject(new Error(`Deriv ${symbol}: connection closed`)));
  });
}
