var FRACTAL = 3;
var HTF_EMA = 50;
var HTF_CHOCH_LOOKBACK = 4;
var H1_MS2 = 36e5;
function qictParams(s) {
  return {
    sl: s.qictStopLoss,
    tp: s.qictTakeProfit,
    minFvg: s.qictMinFvg,
    beAtr: s.qictBreakevenAtr,
    beBuffer: s.qictBreakevenBuffer,
    trailAtr: s.qictTrailAtr,
    chochOn: s.qictRequireChoch,
    chochLookback: s.qictChochLookback,
    htfOn: s.qictHtfFilter,
    atrPeriod: 14
  };
}
function barAt(arr, c, k) {
  if (k < 1) return void 0;
  const i = c - k + 1;
  return i >= 0 && i < arr.length ? arr[i] : void 0;
}
function chochOn(arr, c, bull, lookback) {
  let level = null;
  for (let i = 2; i <= 30 && level === null; i++) {
    const center = barAt(arr, c, i);
    if (!center) break;
    const v = bull ? center.h : center.l;
    let pivot = true;
    for (let k = 1; k <= FRACTAL && pivot; k++) {
      for (const b of [barAt(arr, c, i + k), barAt(arr, c, i - k)]) {
        if (!b) continue;
        if (bull ? b.h > v : b.l < v) {
          pivot = false;
          break;
        }
      }
    }
    if (pivot) level = v;
  }
  if (level === null) return false;
  for (let b = 1; b <= lookback; b++) {
    const x = barAt(arr, c, b);
    if (x && (bull ? x.c > level : x.c < level)) return true;
  }
  return false;
}
function htfIndexAt(h1, closeTime) {
  let idx = -1;
  for (let i = 0; i < h1.length; i++) {
    if (h1[i].t + H1_MS2 <= closeTime) idx = i;
    else break;
  }
  return idx;
}
function qictContext(exec, h1, barMs, atrPeriod = 14) {
  return {
    exec,
    h1,
    h1Ema: ema(h1.map((x) => x.c), HTF_EMA),
    atr: atr(exec, atrPeriod),
    barMs
  };
}
function qictSignal(ctx, c, p) {
  const { exec, h1, h1Ema, barMs } = ctx;
  const b1 = barAt(exec, c, 1), b2 = barAt(exec, c, 2), b3 = barAt(exec, c, 3);
  if (!b1 || !b2 || !b3) return null;
  const hc = htfIndexAt(h1, exec[c].t + barMs);
  if (hc < 0) return null;
  const htfClose = h1[hc].c;
  const htfEma = h1Ema[hc];
  if (!Number.isFinite(htfEma)) return null;
  const chochLtfBull = !p.chochOn || chochOn(exec, c, true, p.chochLookback);
  const chochHtfBull = !p.chochOn || chochOn(h1, hc, true, HTF_CHOCH_LOOKBACK);
  const chochLtfBear = !p.chochOn || chochOn(exec, c, false, p.chochLookback);
  const chochHtfBear = !p.chochOn || chochOn(h1, hc, false, HTF_CHOCH_LOOKBACK);
  const bullTrend = !p.htfOn || htfClose >= htfEma;
  const bearTrend = !p.htfOn || htfClose <= htfEma;
  if (bullTrend && (chochLtfBull || chochHtfBull)) {
    if (b1.l - b3.h >= p.minFvg) {
      return { side: "BUY", kind: "FVG", top: b1.l, bottom: b3.h, mid: (b1.l + b3.h) / 2, htfClose, htfEma, chochLtf: chochLtfBull, chochHtf: chochHtfBull };
    }
    if (b1.c > b1.o && b2.c < b2.o && b1.c > b2.h) {
      return { side: "BUY", kind: "DISPLACEMENT", top: Math.max(b2.o, b2.c), bottom: Math.min(b2.o, b2.c), mid: (b2.o + b2.c) / 2, htfClose, htfEma, chochLtf: chochLtfBull, chochHtf: chochHtfBull };
    }
  }
  if (bearTrend && (chochLtfBear || chochHtfBear)) {
    if (b3.l - b1.h >= p.minFvg) {
      return { side: "SELL", kind: "FVG", top: b3.l, bottom: b1.h, mid: (b3.l + b1.h) / 2, htfClose, htfEma, chochLtf: chochLtfBear, chochHtf: chochHtfBear };
    }
    if (b1.c < b1.o && b2.c > b2.o && b1.c < b2.l) {
      return { side: "SELL", kind: "DISPLACEMENT", top: Math.max(b2.o, b2.c), bottom: Math.min(b2.o, b2.c), mid: (b2.o + b2.c) / 2, htfClose, htfEma, chochLtf: chochLtfBear, chochHtf: chochHtfBear };
    }
  }
  return null;
}
function simulate(ctx, p, from) {
  const { exec } = ctx;
  const n = exec.length;
  const out = [];
  let pos = null;
  let pending = null;
  for (let j = Math.max(from, 0); j < n; j++) {
    const bar = exec[j];
    if (pending) {
      const entry = bar.o;
      const sl = pending.sig.side === "BUY" ? entry - p.sl : entry + p.sl;
      const tp = pending.sig.side === "BUY" ? entry + p.tp : entry - p.tp;
      pos = { side: pending.sig.side, sig: pending.sig, signalIdx: pending.signalIdx, entryIdx: j, entry, stop0: sl, tp0: tp, risk0: p.sl, sl, exitIdx: null, exit: null, r: 0, outcome: "FILLED_OPEN" };
      pending = null;
    }
    if (pos) {
      const hitSL = pos.side === "BUY" ? bar.l <= pos.sl : bar.h >= pos.sl;
      const hitTP = pos.side === "BUY" ? bar.h >= pos.tp0 : bar.l <= pos.tp0;
      if (hitSL || hitTP) {
        const exitPx = hitSL ? pos.sl : pos.tp0;
        const dir = pos.side === "BUY" ? 1 : -1;
        pos.exitIdx = j;
        pos.exit = exitPx;
        pos.r = (exitPx - pos.entry) * dir / pos.risk0;
        pos.outcome = pos.r > 0 ? "FILLED_WIN" : "FILLED_LOSS";
        out.push(pos);
        pos = null;
      } else {
        const a = ctx.atr[j];
        if (Number.isFinite(a) && a > 0) {
          const beDist = p.beAtr * a;
          const tsDist = p.trailAtr * a;
          if (pos.side === "BUY") {
            if (bar.c - pos.entry >= beDist) {
              pos.sl = Math.max(pos.sl, pos.entry + p.beBuffer);
              pos.sl = Math.max(pos.sl, bar.c - tsDist);
            }
          } else if (pos.entry - bar.c >= beDist) {
            pos.sl = Math.min(pos.sl, pos.entry - p.beBuffer);
            pos.sl = Math.min(pos.sl, bar.c + tsDist);
          }
        }
      }
    }
    if (!pos && !pending) {
      const sig = qictSignal(ctx, j, p);
      if (sig && j + 1 < n) pending = { sig, signalIdx: j };
    }
  }
  if (pos) {
    const dir = pos.side === "BUY" ? 1 : -1;
    const last = exec[n - 1].c;
    pos.r = (last - pos.entry) * dir / pos.risk0;
    pos.outcome = "FILLED_OPEN";
    out.push(pos);
  }
  return out;
}
function runQictBacktest(pair, exec, h1, s, windowBars = 32, tf = "M15") {
  const p = qictParams(s);
  const barMs = tf === "M15" ? 15 * 60 * 1e3 : 4 * 60 * 60 * 1e3;
  const n = exec.length;
  const ctx = qictContext(exec, h1, barMs, p.atrPeriod);
  const w0 = Math.max(0, n - windowBars);
  const trades = simulate(ctx, p, w0).filter((t) => t.signalIdx >= w0);
  const now = Date.now();
  const windowFrom = n ? exec[w0].t : 0;
  const windowTo = n ? exec[n - 1].t : 0;
  const setups = trades.map((t) => {
    const id = `QICT-${pair}-${exec[t.signalIdx].t}-${t.side}`;
    const zoneType = t.side === "BUY" ? "DBR" : "RBD";
    return {
      id,
      strategy: "QICT",
      zoneKind: t.sig.kind,
      pair,
      tf,
      side: t.side,
      zoneType,
      trend: t.side === "BUY" ? "UP" : "DOWN",
      obTime: exec[t.signalIdx].t,
      createdAt: exec[t.signalIdx].t + barMs,
      top: t.sig.top,
      bottom: t.sig.bottom,
      entry: t.entry,
      stop: t.stop0,
      tp: t.tp0,
      rr: Math.round(p.tp / p.sl * 100) / 100,
      outcome: t.outcome,
      fillTime: exec[t.entryIdx].t,
      outcomeTime: t.exitIdx !== null ? exec[t.exitIdx].t : null,
      r: Math.round(t.r * 100) / 100,
      recordedAt: now,
      windowFrom,
      windowTo,
      imageKey: `setup:${id}`,
      summary: `QICT ${t.side} \xB7 ${t.sig.kind} \xB7 zone ${t.sig.bottom.toFixed(2)}\u2013${t.sig.top.toFixed(2)} \xB7 H1 ${t.sig.htfClose >= t.sig.htfEma ? "above" : "below"} EMA50 \xB7 ${t.outcome}`
    };
  });
  const taken = { win: 0, loss: 0, open: 0 };
  for (const t of trades) {
    if (t.outcome === "FILLED_WIN") taken.win++;
    else if (t.outcome === "FILLED_LOSS") taken.loss++;
    else taken.open++;
  }
  return {
    pair,
    bars: n - w0,
    loaded: n,
    windowFrom,
    windowTo,
    candidates: trades.length,
    taken,
    invalid: 0,
    setups,
    missed: []
  };
}

