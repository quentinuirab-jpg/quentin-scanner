var WARMUP = 55;
var H4_MS2 = 4 * 60 * 60 * 1e3;
function obAt(c, atrArr, b) {
  const A = c[b - 1], B = c[b], I = c[b + 1];
  const range = B.h - B.l;
  if (!(range > 0)) return null;
  if (Math.abs(B.c - B.o) / range > 0.5) return null;
  const aImp = atrArr[b + 1];
  if (!Number.isFinite(aImp)) return null;
  if (Math.abs(I.c - I.o) < 0.5 * aImp) return null;
  const top = Math.max(B.o, B.c);
  const bottom = Math.min(B.o, B.c);
  if (A.c < A.o && I.c > I.o && I.c > A.h) return { type: "DBR", top, bottom };
  if (A.c > A.o && I.c < I.o && I.c < A.l) return { type: "RBD", top, bottom };
  return null;
}
function runH4Backtest(pair, h4, s, windowBars = 60, tf = "H4") {
  const barMs = tf === "M15" ? 15 * 60 * 1e3 : H4_MS2;
  const n = h4.length;
  if (n < WARMUP + 2) throw new Error(`Backtest needs at least ${WARMUP + 2} complete ${tf} candles (got ${n}).`);
  const closes = h4.map((x) => x.c);
  const e21 = ema(closes, 21), e50 = ema(closes, 50);
  const atrArr = atr(h4, 14);
  const trendAt = (k) => {
    const c = closes[k], a = e21[k], b = e50[k];
    return c > a && a > b ? "UP" : c < a && a < b ? "DOWN" : "MIXED";
  };
  const start = Math.max(WARMUP, n - windowBars);
  const report = {
    pair,
    bars: n - start,
    loaded: n,
    windowFrom: h4[start].t,
    windowTo: h4[n - 1].t,
    candidates: 0,
    taken: { win: 0, loss: 0, open: 0 },
    invalid: 0,
    setups: [],
    missed: []
  };
  const rr = s.riskReward;
  const now = Date.now();
  for (let b = start - 1; b <= n - 3; b++) {
    const k = b + 1;
    if (k < start) continue;
    const ob = obAt(h4, atrArr, b);
    if (!ob) continue;
    const trend = trendAt(k);
    const side = ob.type === "DBR" ? "BUY" : "SELL";
    if (side === "BUY" && trend !== "UP" || side === "SELL" && trend !== "DOWN") continue;
    report.candidates++;
    const buf = s.slBufferAtr * atrArr[k];
    const entry = side === "BUY" ? ob.top : ob.bottom;
    const stop = side === "BUY" ? ob.bottom - buf : ob.top + buf;
    const risk = Math.abs(entry - stop);
    const tp = side === "BUY" ? entry + rr * risk : entry - rr * risk;
    let filledAt = -1;
    let ranAt = -1;
    let invalidAt = -1;
    for (let j = k + 1; j < n; j++) {
      const x = h4[j];
      if (side === "BUY") {
        if (x.l <= entry) {
          filledAt = j;
          break;
        }
        if (x.c < ob.bottom) {
          invalidAt = j;
          break;
        }
        if (x.h >= tp) {
          ranAt = j;
          break;
        }
      } else {
        if (x.h >= entry) {
          filledAt = j;
          break;
        }
        if (x.c > ob.top) {
          invalidAt = j;
          break;
        }
        if (x.l <= tp) {
          ranAt = j;
          break;
        }
      }
    }
    if (invalidAt >= 0) {
      report.invalid++;
      continue;
    }
    const idBase = `${pair}-${tf}-${side}-${h4[b].t}`;
    const base = {
      id: idBase,
      strategy: "QMM",
      pair,
      tf,
      side,
      zoneType: ob.type,
      trend: side === "BUY" ? "UP" : "DOWN",
      obTime: h4[b].t,
      createdAt: h4[k].t + barMs,
      top: ob.top,
      bottom: ob.bottom,
      entry,
      stop,
      tp,
      rr,
      recordedAt: now,
      windowFrom: report.windowFrom,
      windowTo: report.windowTo,
      imageKey: `setup:${idBase}`
    };
    const zoneWord = ob.type === "DBR" ? "demand" : "supply";
    const levels = `${side} limit ${fmt(entry)} \xB7 SL ${fmt(stop)} \xB7 TP ${fmt(tp)}`;
    const zone = `${tf} ${zoneWord} OB ${fmt(ob.bottom)}\u2013${fmt(ob.top)}`;
    if (filledAt >= 0) {
      let res = "open";
      let exitAt = -1;
      for (let j = filledAt; j < n; j++) {
        const x = h4[j];
        const hitStop = side === "BUY" ? x.l <= stop : x.h >= stop;
        const hitTp = side === "BUY" ? x.h >= tp : x.l <= tp;
        if (hitStop) {
          res = "loss";
          exitAt = j;
          break;
        }
        if (hitTp) {
          res = "win";
          exitAt = j;
          break;
        }
      }
      report.taken[res]++;
      const outcome2 = res === "win" ? "FILLED_WIN" : res === "loss" ? "FILLED_LOSS" : "FILLED_OPEN";
      const word2 = res === "win" ? "filled, target hit" : res === "loss" ? "filled, stop hit" : "filled, still open";
      report.setups.push({
        ...base,
        outcome: outcome2,
        fillTime: h4[filledAt].t,
        outcomeTime: exitAt >= 0 ? h4[exitAt].t : null,
        r: res === "win" ? rr : res === "loss" ? -1 : 0,
        summary: `${zone} \xB7 ${levels} \xB7 ${word2}`
      });
      continue;
    }
    const outcome = ranAt >= 0 ? "MISSED_RAN" : "MISSED_UNFILLED";
    const word = outcome === "MISSED_RAN" ? "missed: target ran without a fill" : "missed: entry never filled";
    const setup = {
      ...base,
      outcome,
      fillTime: null,
      outcomeTime: ranAt >= 0 ? h4[ranAt].t : null,
      r: 0,
      summary: `${zone} \xB7 ${levels} \xB7 ${word}`
    };
    report.setups.push(setup);
    report.missed.push(setup);
  }
  return report;
}
