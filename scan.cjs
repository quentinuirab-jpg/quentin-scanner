function alignedSideAt(h1, h4, atMs) {
  return alignment(trendOf(closedBefore(h1, atMs, H1_MS3), "H1"), trendOf(closedBefore(h4, atMs, H4_MS3), "H4")).side;
}
function alignedSideNow(h1, h4) {
  return alignment(trendOf(h1, "H1"), trendOf(h4, "H4")).side;
}

