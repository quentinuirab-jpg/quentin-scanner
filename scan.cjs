function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = a + 1831565813 >>> 0;
    let t = a;
    t = Math.imul(t ^ t >>> 15, t | 1);
    t ^= t + Math.imul(t ^ t >>> 7, t | 61);
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
function gauss(r) {
  let u = 0;
  let v = 0;
  while (u === 0) u = r();
  while (v === 0) v = r();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}
function walkCandles(opts) {
  const r = rng(opts.seed);
  const out = [];
  let p = opts.start;
  for (let i = 0; i < opts.n; i++) {
    const o = p;
    const c = o * (1 + opts.drift + opts.vol * gauss(r));
    const wickUp = Math.abs(gauss(r)) * opts.vol * o * 0.6;
    const wickDn = Math.abs(gauss(r)) * opts.vol * o * 0.6;
    out.push({ t: opts.t0 + i * opts.stepMs, o, h: Math.max(o, c) + wickUp, l: Math.min(o, c) - wickDn, c });
    p = c;
  }
  return out;
}

